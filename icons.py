def _check():
    for name, rows in ICONS.items():
        w = len(rows[0])
        assert all(len(r) == w for r in rows), f"Icon {name}: ungleiche Zeilen"
        assert w <= 16 and len(rows) <= 16, f"Icon {name}: {w}x{len(rows)}"
        assert all(c == "." or c in PALETTE or c == CUSTOM for r in rows for c in r), name


for _n, _a in ANIM.items():
    _h = (len(ICONS[_n]), len(ICONS[_n][0]))
    for _f in _a["frames"] + ([_a["off"]] if _a["off"] else []):
        assert (len(ICONS[_f]), len(ICONS[_f][0])) == _h, f"Animation {_n}: Bild {_f} hat eine andere Größe"
    assert _a["ms"] % 200 == 0, _n


_check()
